/** Rewrite src/plugin/targets/index.ts with only the selected targets. */
export function rewriteTargetsIndex(dir: string, targetIds: string[]): void {
  const selected = targetIds.map((id) => {
    const t = TARGET_SOURCES[id];
    if (!t) throw new Error(`unknown target id: ${id}`);
    return { id, ...t };
  });
  // Group imports by source file, preserving the template's file order.
  const order = [
    "native-claude.ts",
    "native-codex.ts",
    "native-opencode.ts",
    "native-cliagents.ts",
    "skill-agents.ts",
    "plugin-agents.ts",
  ];
  const bySource = new Map<string, { id: string; varName: string }[]>();
  for (const s of selected) {
    const list = bySource.get(s.source) ?? [];
    list.push(s);
    bySource.set(s.source, list);
  }
  const lines: string[] = [
    "// Target adapter registry — generated by create-agent-plugin; edit this",
    "// file to change the target set later (see the README \"Adding a target\" guide).",
    'import type { TargetAdapter } from "../../framework/registry.ts";',
  ];
  for (const src of order) {
    for (const s of bySource.get(src) ?? []) {
      lines.push(`import { ${s.varName} } from "./${src}";`);
    }
  }
  lines.push("");
  lines.push("export const adapters: TargetAdapter[] = [");
  for (const s of selected) lines.push(`  ${s.varName},`);
  lines.push("];");
  lines.push("");
  writeFileSync(join(dir, "src", "plugin", "targets", "index.ts"), lines.join("\n"), "utf8");
}

// ---------------------------------------------------------------- capability tests

/** Test files owned by a demo capability — removed when the capability is
 *  deselected (their assertions would fail without the business they test). */
const CAPABILITY_TESTS: Record<string, string[]> = {
  mcp: ["tests/mcp.test.ts"],
  hook: ["tests/hook-protocol.test.ts"],
  cli: ["tests/cli.test.ts"],
};

// ---------------------------------------------------------------- entry

export interface ScaffoldResult {
  dir: string;
  removedTests: string[];
}

/** Template root: the package root containing src/. Bundled into
 *  dist/generator.js that is file → dist → root (two ".."); in the source
 *  tree scaffold.ts is file → generator → src → root (three ".."). */
function findTemplateRoot(): string {
  const self = fileURLToPath(import.meta.url);
  const inDist = self.split(sep).includes("dist");
  return inDist ? join(self, "..", "..") : join(self, "..", "..", "..");
}

/** Generate a new plugin project. `cwd` is where the target dir is created. */
export async function scaffold(a: GenAnswers, cwd: string): Promise<ScaffoldResult> {
  const templateRoot = findTemplateRoot();
  const dest = join(cwd, a.dir);

  if (existsSync(dest)) {
    const entries = readDirNames(dest);
    if (entries.length > 0) {
      throw new Error(
        `target directory already exists and is not empty: ${dest} (${entries.length} entries) — pick another name or remove it`,
      );
    }
  }

  copyTemplate(templateRoot, dest);
  rewriteManifest(dest, a);
  rewritePackageJson(dest, a);
  rewriteTargetsIndex(dest, a.targets);

  // Remove tests owned by deselected capabilities.
  const removedTests: string[] = [];
  for (const [cap, files] of Object.entries(CAPABILITY_TESTS)) {
    if (a.capabilities.includes(cap)) continue;
    for (const rel of files) {
      const p = join(dest, rel);
      if (existsSync(p)) {
        rmSync(p, { force: true });
        removedTests.push(rel);
      }
    }
  }

  // Fill README placeholders (tokens mirror build.mjs vars). Path-ish tokens
  // (skillDir / configDir / hook) take the unscoped short name; {{name}} keeps
  // the full package name (npx commands).
  //
  // The README template is src/assets/README.md, NOT the package-root
  // README.md: the copied root README is already filled ({{name}} → the
  // template's own identity), so a scaffolded project regenerating a new
  // project would copy a placeholder-free README and keep the OLD identity.
  // The asset copy always carries placeholders — scaffolded projects copy it
  // too (src/assets/ ships), so regeneration is identity-safe.
  const readmeTpl = join(templateRoot, "src", "assets", "README.md");
  if (existsSync(readmeTpl)) {
    const unscoped = unscopedName(a.packageName);
    writeFileSync(
      join(dest, "README.md"),
      fillTemplate(readFileSync(readmeTpl, "utf8"), {
        name: a.packageName,
        brand: a.brand,
        version: "0.1.0",
        description: a.description,
        skillDir: unscoped,
        configDir: `.${unscoped}`,
        hook: `${unscoped}-hook`,
        commandFile: "demo.md",
      }),
      "utf8",
    );
  }

  return { dir: dest, removedTests };
}

/** Print the next steps for the scaffolded project. */
export function printNextSteps(a: GenAnswers, dest: string): void {
  const caps = a.capabilities.join(" + ") || "(none — framework only)";
  process.stdout.write(
    [
      "",
      `Generated ${a.brand} (${a.packageName}) at ${dest}`,
      `  capabilities : ${caps}`,
      `  targets      : ${a.targets.length} — ${a.targets.join(", ")}`,
      "",
      "Next steps:",
      `  cd ${dest}`,
      "  npm install",
      "  npm run verify        # build + typecheck + test",
      `  npm run build && npm pack --dry-run   # manifest check`,
      "",
      "Then fill in the business layer (see README \"What to replace\"):",
      "  src/plugin/tools.ts      — your real MCP tools",
      "  src/plugin/hook.ts       — your real hook handlers",
      "  src/plugin/doctor.ts     — your real doctor checks",
      "  src/plugin/cli-business.ts — your CLI subcommands",
      "",
      "Publishing: bump version in src/plugin/manifest.ts (build injects it",
      "into plugin.json / marketplace.json), commit, and `npm publish`.",
      "",
    ].join("\n"),
  );
}

function readDirNames(p: string): string[] {
  try {
    return readdirSync(p);
  } catch {
    return [];
  }
}
